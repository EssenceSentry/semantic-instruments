import { mkdir, writeFile, readFile } from 'node:fs/promises';
// A deterministic analytic simulation, explicitly separate from empirical weapons data.
const items = [],
  states = [],
  scaled = [];
for (let group = 0; group < 6; group++)
  for (let step = 0; step < 60; step++) {
    const t = step / 12,
      omega = 0.85 + group * 0.14,
      damping = 0.06 + group * 0.025,
      amplitude = 1 + group * 0.2,
      phase = group * 0.35;
    const envelope = amplitude * Math.exp(-damping * t),
      angle = omega * t + phase;
    const x = envelope * Math.cos(angle),
      v = envelope * (-damping * Math.cos(angle) - omega * Math.sin(angle));
    const a =
      envelope *
      ((damping * damping - omega * omega) * Math.cos(angle) +
        2 * damping * omega * Math.sin(angle));
    const energy = 0.5 * (v * v + (omega * omega + damping * damping) * x * x);
    items.push({
      id: `oscillator-${group}-${step}`,
      name: `Oscillator ${group + 1} · t=${t.toFixed(2)}`,
      group: `Oscillator ${group + 1}`,
      category: group < 3 ? 'Gentle damping' : 'Stronger damping',
      label: null,
      scores: { energy, displacement: x, speed: Math.abs(v) },
      annotations: { time: t, angularFrequency: omega, damping },
    });
    states.push([x, v, a, energy]);
    scaled.push([
      x / amplitude,
      v / (amplitude * omega),
      a / (amplitude * omega * omega),
      energy / (amplitude * amplitude),
    ]);
  }
const manifest = {
  schemaVersion: 1,
  id: 'damped-oscillators',
  title: 'Damped oscillators · simulation',
  description:
    'Six analytic damped oscillators sampled at sixty times. A non-classification example for vector geometry, transformations, aggregation, ranking, and sampling.',
  items,
  representations: [
    {
      id: 'state',
      name: 'Physical state',
      kind: 'custom',
      dimensions: 4,
      matrix: { rows: items.length, cols: 4, values: states },
    },
    {
      id: 'scaled',
      name: 'Scale-adjusted state',
      kind: 'custom',
      dimensions: 4,
      matrix: { rows: items.length, cols: 4, values: scaled },
    },
  ],
  primaryScore: 'energy',
  scoreDefinitions: {
    energy: { label: 'Mechanical energy', kind: 'quantity' },
    displacement: { label: 'Signed displacement', kind: 'quantity' },
    speed: { label: 'Absolute speed', kind: 'quantity' },
  },
  presets: { groupBy: 'group' },
  provenance: {
    source: 'Analytic simulation generated by prepare-dynamics.mjs; not empirical measurements',
    equation: 'x(t) = A exp(-λt) cos(ωt+φ); v and a are analytic derivatives; E = (v²+(ω²+λ²)x²)/2',
    units: 'Dimensionless teaching parameters',
    representationColumns: ['position', 'velocity', 'acceleration', 'energy'],
  },
};
await mkdir('public/data/dynamics', { recursive: true });
await writeFile('public/data/dynamics/manifest.json', JSON.stringify(manifest));
const catalog = JSON.parse(await readFile('public/data/catalog.json', 'utf8')).filter(
  (x) => x.id !== manifest.id,
);
catalog.push({
  id: manifest.id,
  title: manifest.title,
  rows: items.length,
  url: '/data/dynamics/manifest.json',
});
await writeFile('public/data/catalog.json', JSON.stringify(catalog));
